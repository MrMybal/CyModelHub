"""Write docs/API.md from the operations the service itself declares.

    python scripts/make_api_doc.py <CyModelHubCli>

The same operations are reachable three ways: the C++ client (Client::invoke), HTTP (POST /v1)
and MCP (tools). Run this after changing an operation in src/service.cpp.
"""

import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent

HEADER = """# CyModelHub service operations

Generated by `scripts/make_api_doc.py` from the running service. Do not edit by hand.

Every operation is available in three ways, with the same name and arguments:

| From | Call |
| --- | --- |
| C++ | `cymodelhub::Client::invoke("models_list", {{"type", "lora"}})` |
| HTTP | `POST <url>/v1` with `{"method":"invoke","name":"models_list","arguments":{"type":"lora"}}` |
| MCP | the tool `models_list`, over `<url>/mcp` or through `CyModelHubMcp` (stdio) |

`<url>` and the access token are in `service.json`, in the CyModelHub data folder
(`%LOCALAPPDATA%\\CyModelHub` on Windows, `~/.local/share/cymodelhub` on Linux,
`~/Library/Application Support/CyModelHub` on macOS). HTTP requests carry
`Authorization: Bearer <token>` and `Content-Type: application/json`; the service listens on
the loopback interface only. A failure is `{"error":{"code":"...","message":"..."}}` with
HTTP 400 or 403; the C++ client throws `cymodelhub::Error` with the same code.

Operations marked *job* return `{"job":"<id>"}` at once; follow it with `jobs_get`
(`Client::wait_job`). A job that failed has a `code` that says why. Operations marked *read*
change nothing.

Every operation that is not a *read* accepts an `idempotencyKey`: sent again with the same key
and the same arguments, it returns its first answer with `"replayed": true` (and the `outcome`
of its job once known) instead of acting a second time; with other arguments it is refused as
`IdempotencyConflict`. Keys are remembered for 7 days, across restarts of the service. The C++
client sends a request again after a lost answer only when that is safe: a *read*, or a request
that carries a key.

[docs/INTEGRATION.md](INTEGRATION.md) shows how an application finds, shares, installs and
registers exactly the model it needs with these operations.

"""


def main():
    cli = str(pathlib.Path(sys.argv[1]).resolve())
    # A service of its own, in an empty folder: the catalogue and the models of the person who
    # runs this script are neither read nor changed.
    scratch = pathlib.Path(tempfile.mkdtemp(prefix="cymodelhub-api-"))
    environment = dict(os.environ, CYMODELHUB_DATA=str(scratch / "data"), HF_HUB_CACHE=str(scratch / "hf"),
                       OLLAMA_MODELS=str(scratch / "ollama"), USERPROFILE=str(scratch / "home"),
                       HOME=str(scratch / "home"))
    (scratch / "home").mkdir()
    try:
        operations = json.loads(subprocess.run([cli, "operations"], capture_output=True, text=True, check=True,
                                               env=environment).stdout)
    finally:
        subprocess.run([cli, "stop"], capture_output=True, env=environment)
        # The service needs a moment to stop and let go of its files.
        for _ in range(30):
            shutil.rmtree(scratch, ignore_errors=True)
            if not scratch.exists():
                break
            time.sleep(0.1)
    lines = [HEADER, "| Operation | | Purpose |", "| --- | --- | --- |"]
    jobs = {"models_move", "models_hash", "scan_start", "install_start", "roots_add", "roots_enable",
            "models_register", "models_verify", "app_updates_download"}
    for operation in operations["operations"]:
        name = operation["name"]
        kind = "read" if operation.get("annotations", {}).get("readOnlyHint") else "job" if name in jobs else "write"
        lines.append(f"| [`{name}`](#{name}) | {kind} | {operation['description'].split('. ')[0].rstrip('.')}. |")
    for operation in operations["operations"]:
        lines += ["", f"## {operation['name']}", "", operation["description"], ""]
        schema = operation["inputSchema"]
        properties = schema.get("properties", {})
        if not properties:
            lines.append("No arguments.")
            continue
        required = set(schema.get("required", []))
        lines += ["| Argument | Type | | Description |", "| --- | --- | --- | --- |"]
        for key, value in properties.items():
            kind = value.get("type", "")
            if "enum" in value:
                kind = " \\| ".join(f"`{item}`" for item in value["enum"])
            elif kind == "array":
                items = value.get("items", {})
                kind = "array of " + (" \\| ".join(f"`{item}`" for item in items["enum"]) if "enum" in items
                                      else items.get("type", "value"))
            lines.append(f"| `{key}` | {kind} | {'required' if key in required else ''} | "
                         f"{value.get('description', '')} |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "API.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(operations['operations'])} operations written to docs/API.md")


if __name__ == "__main__":
    main()
